"""
SQLAlchemy Database Models for CCTV-based Automated Student Attendance System.

This module maps Python objects to PostgreSQL tables defined in our schema.
Includes pgvector support for 512-dimensional facial recognition embeddings.
"""

from datetime import datetime, date, time
from typing import Optional, List, Dict, Any
from sqlalchemy import (
    Column, Integer, BigInteger, String, Text, Date, Time, 
    DateTime, Boolean, Float, ForeignKey, UniqueConstraint, CheckConstraint
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import declarative_base, relationship
from pgvector.sqlalchemy import Vector

Base = declarative_base()


class Student(Base):
    """
    Master table for enrolled students.
    
    Why this structure:
    - roll_no is the official unique college roll number used across departments.
    - department and year allow filtering for section-specific classroom rosters.
    """
    __tablename__ = "students"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    roll_no = Column(String(50), nullable=False, unique=True, index=True)
    name = Column(String(150), nullable=False)
    department = Column(String(100), nullable=False, index=True)
    year = Column(Integer, nullable=False)
    created_at = Column(DateTime(timezone=True), default=datetime.utcnow, nullable=False)

    # Relationships
    face_embeddings = relationship("FaceEmbedding", back_populates="student", cascade="all, delete-orphan")
    attendance_records = relationship("AttendanceRecord", back_populates="student", cascade="all, delete-orphan")
    recognition_events = relationship("RecognitionEvent", back_populates="student")

    __table_args__ = (
        CheckConstraint("year >= 1 AND year <= 5", name="chk_student_year_valid"),
    )

    def __repr__(self) -> str:
        return f"<Student id={self.id} roll_no='{self.roll_no}' name='{self.name}'>"


class FaceEmbedding(Base):
    """
    Stores 512-dimensional ArcFace (Buffalo_L) face embeddings.
    
    Why multiple embeddings per student:
    A student's face varies with camera angles (frontal, left 30°, right 30°) and 
    classroom illumination (morning sunlight, dim projector mode). Storing 8-10 
    distinct vectors per student dramatically increases CCTV identification recall
    compared to storing a single average vector.
    """
    __tablename__ = "face_embeddings"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    student_id = Column(Integer, ForeignKey("students.id", ondelete="CASCADE"), nullable=False, index=True)
    
    # 512-dimensional embedding vector generated by ArcFace (Buffalo_L model)
    embedding = Column(Vector(512), nullable=False)
    
    # Metadata for enrollment quality auditing
    angle_label = Column(String(50), nullable=False)       # e.g., 'frontal', 'profile_left', 'profile_right'
    lighting_label = Column(String(50), nullable=False)    # e.g., 'normal', 'low_light', 'high_exposure'
    captured_at = Column(DateTime(timezone=True), default=datetime.utcnow, nullable=False)

    # Relationships
    student = relationship("Student", back_populates="face_embeddings")

    def __repr__(self) -> str:
        return f"<FaceEmbedding id={self.id} student_id={self.student_id} angle='{self.angle_label}'>"


class Teacher(Base):
    """
    Master table for faculty members.
    
    Why this structure:
    Faculty supervise scheduled lecture periods and hold the authority to approve 
    'needs_review' attendance statuses or apply manual overrides.
    """
    __tablename__ = "teachers"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    name = Column(String(150), nullable=False)
    email = Column(String(255), nullable=False, unique=True, index=True)
    department = Column(String(100), nullable=False)

    # Relationships
    periods = relationship("Period", back_populates="teacher")
    overrides = relationship("TeacherOverride", back_populates="teacher")

    def __repr__(self) -> str:
        return f"<Teacher id={self.id} name='{self.name}' email='{self.email}'>"


class Classroom(Base):
    """
    Physical classroom mapping with CCTV camera RTSP stream endpoints.
    
    Why this structure:
    The background camera ingestion worker spawns a dedicated ingestion thread 
    per active classroom camera RTSP URL.
    """
    __tablename__ = "classrooms"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    name = Column(String(100), nullable=False, unique=True) # e.g., 'LH-101'
    camera_rtsp_url = Column(Text, nullable=False)          # RTSP stream endpoint
    location = Column(String(255), nullable=True)           # e.g., 'Academic Block A, 1st Floor'

    # Relationships
    periods = relationship("Period", back_populates="classroom")
    recognition_events = relationship("RecognitionEvent", back_populates="classroom")

    def __repr__(self) -> str:
        return f"<Classroom id={self.id} name='{self.name}'>"


class Period(Base):
    """
    Scheduled academic timetable slot.
    
    Why period-boundary logic is critical:
    CCTV video feeds run continuously, but attendance must strictly count only 
    for the specific course conducted between start_time and end_time on period_date.
    """
    __tablename__ = "periods"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    classroom_id = Column(Integer, ForeignKey("classrooms.id", ondelete="RESTRICT"), nullable=False, index=True)
    teacher_id = Column(Integer, ForeignKey("teachers.id", ondelete="RESTRICT"), nullable=False, index=True)
    subject = Column(String(150), nullable=False)           # e.g., 'CS401: Computer Vision'
    period_date = Column(Date, nullable=False, index=True)  # Date of class
    start_time = Column(Time, nullable=False)               # e.g., 09:00:00
    end_time = Column(Time, nullable=False)                 # e.g., 10:00:00

    # Relationships
    classroom = relationship("Classroom", back_populates="periods")
    teacher = relationship("Teacher", back_populates="periods")
    attendance_records = relationship("AttendanceRecord", back_populates="period", cascade="all, delete-orphan")
    recognition_events = relationship("RecognitionEvent", back_populates="period", cascade="all, delete-orphan")

    __table_args__ = (
        CheckConstraint("end_time > start_time", name="chk_period_end_after_start"),
    )

    def __repr__(self) -> str:
        return f"<Period id={self.id} subject='{self.subject}' date={self.period_date} {self.start_time}-{self.end_time}>"


class RecognitionEvent(Base):
    """
    Append-only raw log of all face detection and recognition events.
    
    Why an append-only log:
    1. Forensic Auditing: Every detection in video frames is saved with bounding box coordinates.
    2. Anti-Spoofing Audit: Records if MiniFASNet flagged a spoofing attempt (e.g. holding up a phone/photo).
    3. Unidentified Faces: student_id can be NULL if the face was not matched above threshold.
    4. Never edited or overwritten by business logic.
    """
    __tablename__ = "recognition_events"

    id = Column(BigInteger, primary_key=True, index=True, autoincrement=True)
    period_id = Column(Integer, ForeignKey("periods.id", ondelete="CASCADE"), nullable=False, index=True)
    classroom_id = Column(Integer, ForeignKey("classrooms.id", ondelete="CASCADE"), nullable=False, index=True)
    student_id = Column(Integer, ForeignKey("students.id", ondelete="SET NULL"), nullable=True, index=True)
    
    confidence_score = Column(Float, nullable=False)        # Cosine similarity score (0.0 to 1.0)
    is_spoof_flagged = Column(Boolean, default=False, nullable=False, index=True) # Anti-spoofing alert
    bounding_box = Column(JSONB, nullable=False)            # e.g., {"x": 100, "y": 150, "w": 60, "h": 70}
    frame_timestamp = Column(DateTime(timezone=True), nullable=False, index=True)

    # Relationships
    period = relationship("Period", back_populates="recognition_events")
    classroom = relationship("Classroom", back_populates="recognition_events")
    student = relationship("Student", back_populates="recognition_events")

    def __repr__(self) -> str:
        return f"<RecognitionEvent id={self.id} period={self.period_id} student={self.student_id} conf={self.confidence_score:.2f} spoof={self.is_spoof_flagged}>"


class AttendanceRecord(Base):
    """
    Clean derived attendance state consumed by the Live Dashboard and Excel Reports.
    
    Why separate derived table from raw recognition_events:
    1. Query Efficiency: Scanning raw video recognition events (thousands per hour) is too slow for real-time UI.
    2. Confidence-Tiered Status: 
       - 'confirmed'    : High confidence match (score >= CONFIRMED_THRESHOLD) and no spoof flag.
       - 'needs_review' : Marginal confidence (NEEDS_REVIEW_THRESHOLD <= score < CONFIRMED_THRESHOLD).
       - 'unmarked'     : Temporary pending state during ongoing lecture.
       - 'absent'       : No valid detection recorded.
    3. Entry & Exit Tracking: Centroid tracker captures exact timestamps when student arrived and left.
    4. Deduplication: UNIQUE(student_id, period_id) enforces strictly one attendance state per student per period.
    """
    __tablename__ = "attendance_records"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    student_id = Column(Integer, ForeignKey("students.id", ondelete="CASCADE"), nullable=False, index=True)
    period_id = Column(Integer, ForeignKey("periods.id", ondelete="CASCADE"), nullable=False, index=True)
    
    status = Column(String(20), nullable=False, index=True) # 'confirmed', 'needs_review', 'unmarked', 'absent'
    confidence_score = Column(Float, nullable=True)         # Representative matching score
    entry_time = Column(DateTime(timezone=True), nullable=True) # First tracked frame timestamp
    exit_time = Column(DateTime(timezone=True), nullable=True)  # Last tracked frame timestamp
    marked_by = Column(String(50), default="system", nullable=False) # 'system' or 'teacher'
    
    created_at = Column(DateTime(timezone=True), default=datetime.utcnow, nullable=False)
    updated_at = Column(DateTime(timezone=True), default=datetime.utcnow, onupdate=datetime.utcnow, nullable=False)

    # Relationships
    student = relationship("Student", back_populates="attendance_records")
    period = relationship("Period", back_populates="attendance_records")
    overrides = relationship("TeacherOverride", back_populates="attendance_record", cascade="all, delete-orphan")

    __table_args__ = (
        UniqueConstraint("student_id", "period_id", name="uq_student_period"),
        CheckConstraint("status IN ('confirmed', 'needs_review', 'unmarked', 'absent')", name="chk_attendance_status_valid"),
    )

    def __repr__(self) -> str:
        return f"<AttendanceRecord id={self.id} student={self.student_id} period={self.period_id} status='{self.status}'>"


class TeacherOverride(Base):
    """
    Immutable audit trail for faculty manual attendance modifications.
    
    Why an audit trail is required:
    Preserves academic accountability. If a teacher overrides an automated 'absent'
    or 'needs_review' to 'confirmed' (or vice-versa), the system records who made the change,
    the timestamp, previous vs new status, and the compulsory justification reason.
    """
    __tablename__ = "teacher_overrides"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    attendance_record_id = Column(Integer, ForeignKey("attendance_records.id", ondelete="CASCADE"), nullable=False, index=True)
    teacher_id = Column(Integer, ForeignKey("teachers.id", ondelete="RESTRICT"), nullable=False, index=True)
    
    previous_status = Column(String(20), nullable=False)
    new_status = Column(String(20), nullable=False)
    reason = Column(Text, nullable=False)                   # e.g., 'Student was seated in CCTV blind spot'
    overridden_at = Column(DateTime(timezone=True), default=datetime.utcnow, nullable=False)

    # Relationships
    attendance_record = relationship("AttendanceRecord", back_populates="overrides")
    teacher = relationship("Teacher", back_populates="overrides")

    __table_args__ = (
        CheckConstraint("new_status IN ('confirmed', 'needs_review', 'unmarked', 'absent')", name="chk_override_status_valid"),
    )

    def __repr__(self) -> str:
        return f"<TeacherOverride id={self.id} record={self.attendance_record_id} by teacher={self.teacher_id} {self.previous_status}->{self.new_status}>"
